import { writeFile } from 'node:fs/promises';
import { CONFIG } from '../config.js';

// Public visualization built from IMDb's chart on 2026-08-20. IMDb's chart page
// itself is protected by a browser challenge, so this is an explicit snapshot
// source rather than a runtime dependency of the TV app.
const SOURCE_URL = 'https://public.flourish.studio/visualisation/30059219/embed';
const SNAPSHOT_DATE = '2026-08-20';

const normalize = value => String(value || '')
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .replace(/&/g, 'and')
  .replace(/[^a-z0-9]+/gi, '')
  .toLowerCase();

const aliases = new Map([
  ['seven', 'Se7en'],
  ['starwarsepisodevtheempirestrikesback', 'The Empire Strikes Back'],
  ['starwarsepisodeivanewhope', 'Star Wars'],
  ['starwarsepisodevireturnofthejedi', 'Return of the Jedi'],
  ['witnessforprosecution', 'Witness for the Prosecution'],
  ['terminator2judgementday', 'Terminator 2: Judgment Day'],
  ['ingloriousbasterds', 'Inglourious Basterds'],
  ['walle', 'WALL·E'],
  ['dasbot', 'Das Boot'],
  ['requimforadream', 'Requiem for a Dream'],
  ['aseperation', 'A Separation'],
  ['judgementatnuremberg', 'Judgment at Nuremberg'],
  ['thepassionofjoanarc', 'The Passion of Joan of Arc'],
]);

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}`);
  return response.json();
}

async function resolveMovie(row) {
  const sourceTitle = row.name[0];
  const queryTitle = aliases.get(normalize(sourceTitle)) || sourceTitle;
  const year = Math.floor(row.x);
  const params = new URLSearchParams({
    api_key: CONFIG.API_KEY,
    query: queryTitle,
    include_adult: 'false',
    primary_release_year: String(year),
  });
  let data = await fetchJson(`${CONFIG.BASE_URL}/search/movie?${params}`);
  let exact = data.results?.find(movie => normalize(movie.title) === normalize(queryTitle));
  if (!exact) {
    params.delete('primary_release_year');
    data = await fetchJson(`${CONFIG.BASE_URL}/search/movie?${params}`);
    exact = data.results?.find(movie => normalize(movie.title) === normalize(queryTitle));
  }
  const movie = exact || data.results?.[0];
  if (!movie) throw new Error(`No TMDB match for #${row.y} ${sourceTitle} (${year})`);
  return {
    ...movie,
    media_type: 'movie',
    imdb_rank: row.y,
    imdb_title: sourceTitle,
    imdb_year: year,
  };
}

const html = await (await fetch(SOURCE_URL)).text();
const marker = '_Flourish_data = ';
const start = html.indexOf(marker);
if (start < 0) throw new Error('Could not locate Flourish chart data');
const jsonStart = start + marker.length;
let depth = 0;
let quoted = false;
let escaped = false;
let jsonEnd = -1;
for (let i = jsonStart; i < html.length; i++) {
  const char = html[i];
  if (quoted) {
    if (escaped) escaped = false;
    else if (char === '\\') escaped = true;
    else if (char === '"') quoted = false;
    continue;
  }
  if (char === '"') quoted = true;
  else if (char === '{') depth++;
  else if (char === '}' && --depth === 0) { jsonEnd = i + 1; break; }
}
if (jsonEnd < 0) throw new Error('Could not find end of Flourish chart data');
const rows = JSON.parse(html.slice(jsonStart, jsonEnd)).data
  .sort((a, b) => a.y - b.y);
if (rows.length !== 250) throw new Error(`Expected 250 IMDb rows, found ${rows.length}`);

const movies = new Array(rows.length);
let cursor = 0;
async function worker() {
  while (cursor < rows.length) {
    const index = cursor++;
    movies[index] = await resolveMovie(rows[index]);
    process.stdout.write(`\rResolved ${index + 1}/250`);
  }
}
await Promise.all(Array.from({ length: 6 }, worker));
process.stdout.write('\n');

const mismatches = movies.filter(movie => (
  normalize(movie.title) !== normalize(aliases.get(normalize(movie.imdb_title)) || movie.imdb_title)
));
if (mismatches.length) {
  console.error('Review TMDB matches:');
  for (const movie of mismatches) {
    console.error(`#${movie.imdb_rank} ${movie.imdb_title} (${movie.imdb_year}) -> ${movie.title} (${movie.release_date})`);
  }
  process.exitCode = 1;
}

const output = `// Generated by scripts/update-imdb-top250.mjs.\n`
  + `// IMDb chart snapshot: ${SNAPSHOT_DATE}. Do not reorder: array order is rank order.\n`
  + `export const IMDB_TOP_250_SNAPSHOT_DATE = '${SNAPSHOT_DATE}';\n`
  + `export const IMDB_TOP_250 = ${JSON.stringify(movies, null, 2)};\n`;
await writeFile(new URL('../imdb-top250.js', import.meta.url), output);
