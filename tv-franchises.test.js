import test from 'node:test';
import assert from 'node:assert/strict';
import { FRANCHISES } from './franchises.js';
import { franchiseCard, franchiseRow, franchiseSpan, firstUnfinishedIndex } from './tv-franchises.mjs';

const part = (id, date, extra = {}) => ({ id, title: `Part ${id}`, release_date: date, poster_path: `/p${id}.jpg`, backdrop_path: `/b${id}.jpg`, vote_average: 7, vote_count: 900, ...extra });
const matrix = { id: 'franchise:2344', collectionId: 2344, title: 'The Matrix', overview: 'Wake up.', backdrop_path: '/m.jpg', poster_path: '/mp.jpg', parts: [part(1, '1999-03-31'), part(2, '2003-05-15'), part(3, '2003-11-05')] };

test('franchiseSpan: how many films and over which years', () => {
  assert.deepEqual(franchiseSpan(matrix), { count: 3, from: 1999, to: 2003, label: '3 films  ·  1999-2003' });
  assert.equal(franchiseSpan({ parts: [part(1, '2001-01-01'), part(2, '2001-12-01')] }).label, '2 films  ·  2001', 'one year is not a range');
  assert.equal(franchiseSpan({ parts: [part(1, '2001-01-01')] }).label, '1 film  ·  2001', 'singular');
});

test('franchiseCard: a tile that carries its franchise and is not mistaken for a film', () => {
  const card = franchiseCard(matrix);
  assert.equal(card.id, 'franchise:2344');
  assert.equal(card.title, 'The Matrix');
  assert.equal(card.media_type, 'franchise');
  assert.equal(card.franchise, matrix);
  assert.equal(card.backdrop_path, '/m.jpg');
  assert.equal(card.release_date, '1999-03-31', 'sorts/ages by its first film');
  assert.equal(card.vote_average, 0, 'no star rating on a franchise tile: it shows its film count instead');
  assert.equal(card.filmCount, 3);
});

test('franchiseRow: on the All and Movies homes only, never on TV, never empty', () => {
  const row = franchiseRow('all', [matrix]);
  assert.equal(row.key, 'franchises');
  assert.equal(row.title, 'Franchises');
  assert.equal(row.items.length, 1);
  assert.equal(row.items[0].media_type, 'franchise');
  assert.equal(row.noSort, true, 'curated order (most popular series first): the generic row sort by rating must not reorder it');
  assert.ok(franchiseRow('movie', [matrix]));
  assert.equal(franchiseRow('tv', [matrix]), null, 'series are not films');
  assert.equal(franchiseRow('live', [matrix]), null);
  assert.equal(franchiseRow('all', []), null);
  assert.equal(franchiseRow('all', undefined), null);
});

test('firstUnfinishedIndex: opens on the next part you have not finished', () => {
  const progress = map => id => map[id] || 0;
  assert.equal(firstUnfinishedIndex(matrix.parts, progress({})), 0, 'nothing watched: Part 1');
  assert.equal(firstUnfinishedIndex(matrix.parts, progress({ 1: 0.97 })), 1, 'Part 1 finished: Part 2');
  assert.equal(firstUnfinishedIndex(matrix.parts, progress({ 1: 0.98, 2: 0.4 })), 1, 'halfway through Part 2: stay on it');
  assert.equal(firstUnfinishedIndex(matrix.parts, progress({ 1: 0.99, 2: 0.99, 3: 0.99 })), 0, 'all finished: start again');
  assert.equal(firstUnfinishedIndex(matrix.parts, undefined), 0, 'no progress source');
});

// ---- the baked data (franchises.js, generated by scripts/build-franchises.mjs) ----
test('franchises.js: the series the user asked for are there, in order, complete enough to trust', () => {
  assert.ok(FRANCHISES.length >= 60, `expected a full catalogue, got ${FRANCHISES.length}`);
  const byTitle = Object.fromEntries(FRANCHISES.map(f => [f.title, f]));
  for (const t of ['Fast & Furious', 'The Matrix', 'Shrek', 'Harry Potter', 'Star Wars', 'The Lord of the Rings', 'Marvel Cinematic Universe', 'James Bond']) assert.ok(byTitle[t], `${t} is listed`);
  assert.ok(byTitle['Fast & Furious'].parts.length >= 10);
  assert.deepEqual(byTitle['The Matrix'].parts.slice(0, 3).map(p => p.title), ['The Matrix', 'The Matrix Reloaded', 'The Matrix Revolutions'], 'Part 1, 2, 3 in release order');
  assert.deepEqual(byTitle['Shrek'].parts.slice(0, 3).map(p => p.title), ['Shrek', 'Shrek 2', 'Shrek the Third']);
  const mcu = byTitle['Marvel Cinematic Universe'];
  assert.ok(mcu.parts.length >= 35, `the MCU has ${mcu.parts.length} films`);
  assert.deepEqual(mcu.parts.slice(0, 3).map(p => p.title), ['Iron Man', 'The Incredible Hulk', 'Iron Man 2']);
  for (const junk of ['Ultimate Avengers 2', 'Ghost Rider', 'Team Thor', 'Groot Takes a Bath']) assert.ok(!mcu.parts.some(p => p.title === junk), `${junk} is not an MCU film`);
});

test('franchises.js: every franchise is well formed (a wrong regeneration must fail loudly)', () => {
  const ids = new Set(); const titles = new Set(); const today = new Date().toISOString().slice(0, 10);
  for (const f of FRANCHISES) {
    assert.match(String(f.id), /^franchise:/);
    assert.ok(!ids.has(f.id) && !titles.has(f.title), `${f.title}: duplicate`);
    ids.add(f.id); titles.add(f.title);
    assert.ok(f.poster_path && f.backdrop_path, `${f.title}: artwork`);
    assert.ok(f.parts.length >= 3, `${f.title}: a franchise has at least 3 films`);
    const partIds = new Set();
    f.parts.forEach((p, i) => {
      assert.ok(p.id && p.title && p.poster_path, `${f.title} part ${i + 1}: id, title, poster`);
      assert.ok(!partIds.has(p.id), `${f.title}: part ${p.title} repeated`);
      partIds.add(p.id);
      assert.ok(p.release_date <= today, `${f.title}: ${p.title} is not released yet`);
      if (i) assert.ok(f.parts[i - 1].release_date <= p.release_date, `${f.title}: parts out of release order at ${p.title}`);
    });
  }
});

// ---- Audited against an independent TMDB title search (TMDB's own collections are incomplete: sequels left unlinked, series
// split in several collections). These are the counts the audit settled on; a regeneration that loses a film must fail here.
test('franchises.js: audited film counts and the films TMDB never linked (The Matrix is 4, not 3)', () => {
  const by = Object.fromEntries(FRANCHISES.map(f => [f.title, f]));
  const counts = { 'The Matrix': 4, 'Star Wars': 12, 'Harry Potter': 8, 'Fantastic Beasts': 3, 'Shrek': 4, 'The Lord of the Rings': 4, 'The Hobbit': 3, 'Star Trek': 13,
    'Halloween': 13, 'Planet of the Apes': 10, 'X-Men': 10, 'Alien': 9, 'Predator': 9, 'Transformers': 8, 'Despicable Me': 7, 'Resident Evil': 8, "Ocean's": 5,
    'Evil Dead': 6, 'John Wick': 5, 'Marvel Cinematic Universe': 38, 'Fast & Furious': 11 };
  for (const [title, n] of Object.entries(counts)) assert.equal(by[title] && by[title].parts.length, n, `${title} has ${n} films`);
  const titles = t => by[t].parts.map(p => p.title);
  assert.equal(titles('The Matrix').at(-1), 'The Matrix Resurrections', 'TMDB does not link it to the Matrix collection');
  for (const t of ['Rogue One: A Star Wars Story', 'Solo: A Star Wars Story']) assert.ok(titles('Star Wars').includes(t), t);
  assert.ok(titles('Star Trek').includes('Star Trek: Nemesis') && titles('Star Trek').includes('Star Trek Beyond'), 'the Next Generation and the 2009 films are folded in');
  assert.equal(titles('Planet of the Apes')[0], 'Planet of the Apes', 'the 1968 original leads');
  assert.ok(titles('Alien').includes('Alien: Romulus') && titles('Alien').includes('Prometheus'));
  assert.ok(titles('X-Men').includes('Logan'));
  assert.ok(titles('Transformers').includes('Bumblebee') && titles('Transformers').includes('Transformers One'));
});

test('franchises.js: no documentaries, TV specials, making-ofs or shorts slipped in', () => {
  const junk = /(holiday special|return to hogwarts|making of|behind the|one-shot|assembled|a mammoth christmas|shrek the halls|scared shrekless|toy story of terror|that time forgot)/i;
  for (const f of FRANCHISES) for (const p of f.parts) assert.ok(!junk.test(p.title), `${f.title}: "${p.title}" is not a feature film of the series`);
});
